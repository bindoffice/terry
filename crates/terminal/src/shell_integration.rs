    #[test]
    fn injection_is_idempotent() {
        let mut env = HashMap::default();
        env.insert("ZDOTDIR".to_string(), "/user/zsh".to_string());
        let _ = inject_with_dir(&mut env, "zsh", Path::new("/integration"));
        let injected = env.clone();
        // Re-running the injection (as `clone_builder` does) must not clobber
        // the saved user ZDOTDIR with the shim directory.
        let _ = inject_with_dir(&mut env, "zsh", Path::new("/integration"));
        assert_eq!(env, injected);
        assert_eq!(
            env.get(TERRY_USER_ZDOTDIR_ENV).map(String::as_str),
            Some("/user/zsh")
        );
    }

    #[test]
    fn cli_path_is_prepended_without_duplicates() {
        assert_eq!(prepend_path(None, "/app/bin"), "/app/bin");
        assert_eq!(prepend_path(Some(""), "/app/bin"), "/app/bin");

        let existing = format!("/usr/bin{PATH_SEPARATOR}/bin");
        let expected = format!("/app/bin{PATH_SEPARATOR}{existing}");
        assert_eq!(prepend_path(Some(&existing), "/app/bin"), expected);

        // Re-injecting (as `clone_builder` does) must not add the directory twice.
        let already = format!("/app/bin{PATH_SEPARATOR}/usr/bin");
        assert_eq!(prepend_path(Some(&already), "/app/bin"), already);
    }

    #[test]
    fn cli_shims_expose_terry_and_terry_daemon() {
        let dir = std::env::temp_dir().join(format!(
            "terry-cli-shims-{}-{}",
            std::process::id(),
            std::time::SystemTime::now()
                .duration_since(std::time::UNIX_EPOCH)
                .unwrap()
                .as_nanos()
        ));
        let exe = Path::new("/Applications/Terry App/Contents/MacOS/terry");
        let mut env = HashMap::default();
        env.insert("PATH".to_string(), "/usr/bin".to_string());

        install_cli_shims(&mut env, &dir, exe).unwrap();

        let expected_path = format!("{}{PATH_SEPARATOR}/usr/bin", dir.display());
        assert_eq!(
            env.get("PATH").map(String::as_str),
            Some(expected_path.as_str())
        );

        // Installing again is a no-op and must not duplicate the entry.
        install_cli_shims(&mut env, &dir, exe).unwrap();
        assert_eq!(
            env.get("PATH").map(String::as_str),
            Some(expected_path.as_str())
        );

        let terry = std::fs::read_to_string(dir.join(shim_file_name("terry"))).unwrap();
        let daemon_name = shim_file_name("terry-daemon");
        let daemon = std::fs::read_to_string(dir.join(&daemon_name)).unwrap();

        #[cfg(unix)]
        {
            // The executable path is quoted, so spaces in the app bundle work.
            assert!(terry.contains("exec '/Applications/Terry App/Contents/MacOS/terry' \"$@\""));
            // `terry-daemon list` must run `terry daemon list`.
            assert!(
                daemon
                    .contains("exec '/Applications/Terry App/Contents/MacOS/terry' daemon \"$@\"")
            );
            use std::os::unix::fs::PermissionsExt as _;
            let mode = std::fs::metadata(dir.join(&daemon_name))
                .unwrap()
                .permissions()
                .mode();
            assert_eq!(mode & 0o111, 0o111, "the daemon shim must be executable");
        }
        #[cfg(windows)]
        {
            assert!(daemon.contains("\"/Applications/Terry App/Contents/MacOS/terry\" daemon %*"));
        }

        std::fs::remove_dir_all(&dir).ok();
    }

    #[cfg(unix)]
    #[test]
